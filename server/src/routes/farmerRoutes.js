const express = require("express");
const router = express.Router();
const c = require("../controllers/farmerController");
const { auth } = require("../middleware/auth");
const { role } = require("../middleware/role");
const { approvedFarmer } = require("../middleware/approvedFarmer");
const { uploadFarm } = require("../middleware/upload");
const { uploadLand } = require("../middleware/upload");
router.get("/", c.list);
router.get("/profile", auth, role("farmer"), c.getProfile);
router.put("/profile", auth, role("farmer"), c.updateProfile);
router.post("/profile/land-document", auth, role("farmer"), uploadLand.single("document"), c.uploadLandDocument);
router.get("/profile/land-document", auth, role("farmer"), c.downloadLandDocument);
router.delete("/profile/land-document", auth, role("farmer"), c.removeLandDocument);
router.put("/me", auth, role("farmer"), approvedFarmer, uploadFarm.single("photo"), c.updateMe);
router.put("/me/location", auth, role("farmer"), approvedFarmer, c.updateLocation);
router.get("/:id", c.get);
module.exports = router;
