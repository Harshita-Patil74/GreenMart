const mongoose = require("mongoose");
const OrderItemSchema = new mongoose.Schema({
  product: { type: mongoose.Schema.Types.ObjectId, ref: "Product" },
  name: String,
  price: Number,
  quantity: Number,
  image: String,
  farmer: { type: mongoose.Schema.Types.ObjectId, ref: "User" },
  offerSnapshot: {
    offerId: { type: mongoose.Schema.Types.ObjectId, ref: "Offer" },
    offerTitle: String,
    offerType: String,
    discountType: String,
    discountValue: Number,
    isSubscriberExclusive: Boolean,
    isPremiumExclusive: Boolean,
    originalUnitPrice: Number,
    appliedDiscount: Number,
    premiumDiscount: Number,
    finalUnitPrice: Number,
    finalLineTotal: Number,
  },
  fulfillmentStatus: String,
  deliveryFailureReason: String,
  fulfillmentHistory: [{ status: String, reason: String, at: { type: Date, default: Date.now } }],
});
const OrderSchema = new mongoose.Schema({
  orderNumber: { type: String, unique: true },
  user: { type: mongoose.Schema.Types.ObjectId, ref: "User", required: true },
  items: [OrderItemSchema],
  address: { name: String, line1: String, city: String, state: String, postalCode: String, phone: String },
  coordinates: { lat: Number, lng: Number },
  paymentMethod: String,
  paymentStatus: { type: String, default: "Pending" },
  status: { type: String, default: "Order Placed" },
  statusHistory: [{ status: String, reason: String, at: { type: Date, default: Date.now } }],
  subtotal: Number,
  regularDiscount: Number,
  premiumDiscount: Number,
  deliveryCharge: Number,
  discount: Number,
  tax: Number,
  total: Number,
  invoiceNumber: { type: String, unique: true, sparse: true },
  invoiceGeneratedAt: Date,
  invoiceStatus: { type: String },
  estimatedDelivery: Date,
  currentLocation: { lat: Number, lng: Number, updatedAt: Date },
  isDemo: { type: Boolean, default: false } }, { timestamps: true });
module.exports = mongoose.model("Order", OrderSchema);
