import api from "./axiosInstance";

export default {
  list: () => api.get("/farmers"),
  get: (id) => api.get(`/farmers/${id}`),
  updateMe: (d) => api.put("/farmers/me", d),
  updateLocation: (d) => api.put("/farmers/me/location", d),
  profile: () => api.get("/farmers/profile"),
  updateProfile: (d) => api.put("/farmers/profile", d),
  uploadLandDocument: (file) => { const fd = new FormData(); fd.append("document", file); return api.post("/farmers/profile/land-document", fd); },
  downloadLandDocument: () => api.get("/farmers/profile/land-document", { responseType: "blob" }),
  removeLandDocument: () => api.delete("/farmers/profile/land-document"),
  harvests: () => api.get("/farmers/harvests"),
  createHarvest: (d) => api.post("/farmers/harvests", d),
  getHarvest: (id) => api.get(`/farmers/harvests/${id}`),
  updateHarvest: (id, d) => api.put(`/farmers/harvests/${id}`, d),
  updateHarvestAvailability: (id, d) => api.patch(`/farmers/harvests/${id}/availability`, d),
  deleteHarvest: (id) => api.delete(`/farmers/harvests/${id}`),
  crops: () => api.get("/farmers/crops"),
  salesOverview: () => api.get("/farmers/sales/overview"),
  sales: () => api.get("/farmers/sales"),
  createInventoryAdjustment: (id, d) => api.post(`/farmers/inventory/${id}/adjustments`, d),
  inventoryHistory: (id) => api.get(`/farmers/inventory/${id}/history`),
  allInventoryHistory: () => api.get("/farmers/inventory/history"),
  consolidatedInventory: () => api.get("/farmers/inventory"),
  inventory: () => api.get("/farmers/inventory"),
  getCrop: (id) => api.get(`/farmers/crops/${id}`),
  updateCrop: (id, d) => api.put(`/farmers/crops/${id}`, d),
  deleteCrop: (id) => api.delete(`/farmers/crops/${id}`),
  locations: () => api.get("/locations"),
};